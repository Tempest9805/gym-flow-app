/**
 * generate-media-index.js
 *
 * Scans assets/exercises/normalized/*.webp and generates
 * lib/utils/mediaMap.ts — a static require() map consumed by useLocalMedia.
 *
 * Run after every new batch of WebP conversions:
 *   node scripts/generate-media-index.js
 *
 * WHY STATIC REQUIRE()?
 * React Native / Metro cannot resolve truly dynamic require() calls at bundle
 * time.  The only safe pattern is a static object of pre-resolved require()
 * calls generated ahead of time.
 */

'use strict';

const fs   = require('fs');
const path = require('path');

const ROOT       = path.join(__dirname, '..');
const THUMB_DIR  = path.join(ROOT, 'assets', 'exercises', 'thumbs');
const NORM_DIR   = path.join(ROOT, 'assets', 'exercises', 'normalized');
const HIRES_DIR  = path.join(ROOT, 'assets', 'exercises', 'hires');
const OUT_FILE   = path.join(ROOT, 'lib', 'utils', 'mediaMap.ts');

function ensureDir(d) {
  if (!fs.existsSync(d)) fs.mkdirSync(d, { recursive: true });
}

function main() {
  if (!fs.existsSync(NORM_DIR)) {
    console.log('⚠️  normalized/ directory not found — run convert-to-webp.js first.');
    // Write an empty map so the app still compiles
    ensureDir(path.dirname(OUT_FILE));
    writeMap([]);
    return;
  }

  const files = fs.readdirSync(NORM_DIR).filter(f => f.endsWith('.webp'));
  console.log(`📦  Found ${files.length} WebP files in normalized/`);
  writeMap(files);
  console.log(`✅  Generated: lib/utils/mediaMap.ts`);
}

function writeMap(files) {
  ensureDir(path.dirname(OUT_FILE));

  const entriesThumb = files.map(f => {
    const slug = f.replace(/\.webp$/, '');
    const p = `../../assets/exercises/thumbs/${f}`;
    return `  '${slug}': require('${p}'),`;
  });

  const entriesNorm = files.map(f => {
    const slug = f.replace(/\.webp$/, '');
    const p = `../../assets/exercises/normalized/${f}`;
    return `  '${slug}': require('${p}'),`;
  });

  const entriesHires = files.map(f => {
    const slug = f.replace(/\.webp$/, '');
    const p = `../../assets/exercises/hires/${f}`;
    // Not all might have hires if we didn't force, but let's assume they exist if norm exists or we can just point to it.
    // Actually, require() throws if the file doesn't exist, so we should check existence first.
    return fs.existsSync(path.join(HIRES_DIR, f)) ? `  '${slug}': require('${p}'),` : null;
  }).filter(Boolean);

  const content = [
    '/**',
    ' * mediaMap.ts — AUTO-GENERATED by scripts/generate-media-index.js',
    ' * DO NOT EDIT MANUALLY.',
    ' *',
    ' * Re-generate after running: node scripts/convert-to-webp.js',
    ' *   node scripts/generate-media-index.js',
    ' */',
    '',
    '// eslint-disable-next-line @typescript-eslint/no-explicit-any',
    'export const THUMB_MAP: Record<string, any> = {',
    ...entriesThumb,
    '};',
    '',
    '// eslint-disable-next-line @typescript-eslint/no-explicit-any',
    'export const NORMALIZED_MAP: Record<string, any> = {',
    ...entriesNorm,
    '};',
    '',
    '// eslint-disable-next-line @typescript-eslint/no-explicit-any',
    'export const HIRES_MAP: Record<string, any> = {',
    ...entriesHires,
    '};',
    '',
  ].join('\n');

  fs.writeFileSync(OUT_FILE, content, 'utf8');
}

main();
